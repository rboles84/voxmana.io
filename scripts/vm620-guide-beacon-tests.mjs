import assert from "node:assert/strict";
import { readdir, readFile, stat } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const read = (relativePath) => readFile(path.join(root, relativePath), "utf8");

const [
  homeHtml,
  archscryHtml,
  mazeHtml,
  dossierView,
  mazeUi,
  beaconCss,
  beaconJs,
  topbarJs,
  guideHtml,
  readingGuideHtml,
  mazeGuideHtml,
] = await Promise.all([
  read("index.html"),
  read("archscry/index.html"),
  read("maze/index.html"),
  read("assets/js/archscry/runtime/dossier-view.js"),
  read("assets/js/maze/research-ui.js"),
  read("assets/css/guide-beacon.css"),
  read("assets/js/shared/guide-beacon.js"),
  read("assets/js/shared/vm-topbar.js"),
  read("guide/index.html"),
  read("guide/reading/index.html"),
  read("guide/maze/index.html"),
]);

const expectedBeaconOwners = new Map([
  ["index.html", "home-guide-entry"],
  ["index_old.html", "home-guide-entry"], // Owner-requested original Home backup.
  ["assets/js/archscry/runtime/dossier-view.js", "dossier-reading-help"],
  ["assets/js/maze/research-ui.js", "maze-search-help"],
]);

const ignoredDirectories = new Set([".git", "docs", "node_modules", "outputs", "scripts", "tests", "vendor"]);
const beaconOwners = [];

async function scanRuntime(relativeDirectory = "") {
  const absoluteDirectory = path.join(root, relativeDirectory);
  for (const entry of await readdir(absoluteDirectory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (ignoredDirectories.has(entry.name) || (relativeDirectory === "assets" && entry.name === "vendor")) continue;
      await scanRuntime(path.join(relativeDirectory, entry.name));
      continue;
    }
    if (!/\.(?:html|js)$/.test(entry.name)) continue;
    const relativePath = path.join(relativeDirectory, entry.name).replaceAll("\\", "/");
    const source = await read(relativePath);
    for (const match of source.matchAll(/data-guide-beacon-id="([^"]+)"/g)) {
      beaconOwners.push({ path: relativePath, id: match[1] });
    }
  }
}

await scanRuntime();
assert.deepEqual(
  beaconOwners.sort((a, b) => a.path.localeCompare(b.path)),
  [...expectedBeaconOwners].map(([ownerPath, id]) => ({ path: ownerPath, id })).sort((a, b) => a.path.localeCompare(b.path)),
  "only the three approved contextual surfaces and preserved Home backup should own Guide Beacons",
);

assert.match(homeHtml, /class="vm-guide-beacon vm-guide-beacon--entry"[^>]*href="\.\/guide\/\?guided=vox-mana-intro"[^>]*data-guide-beacon-id="home-guide-entry"/);
assert.match(homeHtml, /Field Guide[\s\S]*?New to Vox Mana\?[\s\S]*?Start with the Guide/);

assert.match(dossierView, /class="dossier-orientation-guide vm-guide-beacon vm-guide-beacon--compact"[^>]*href="\.\.\/guide\/reading\/\?guided=dossier-reading"[^>]*data-guide-beacon-id="dossier-reading-help"/);
assert.match(dossierView, /Field Guide[\s\S]*?How to read your dossier/);

assert.match(mazeUi, /class="qi-guide-link vm-guide-beacon vm-guide-beacon--maze"[^>]*href="\.\.\/guide\/maze\/\?guided=maze-search"[^>]*data-guide-beacon-id="maze-search-help"/);
assert.match(mazeUi, /Field Guide[\s\S]*?Walk me through this search/);
assert.doesNotMatch(mazeUi, /hasPresentedGuideBeaconSignal|reserveGuideBeaconSignal|bindGuideBeaconSignal/, "Maze should use the shared attention owner");

for (const [route, source] of [["Home", homeHtml], ["Archscry", archscryHtml], ["Maze", mazeHtml]]) {
  assert.match(source, /guide-beacon\.css\?v=vm620/, `${route} should load shared Beacon CSS`);
  assert.match(source, /guide-beacon\.js\?v=vm620/, `${route} should load shared Beacon enhancement JS`);
}
for (const [route, source] of [["Guide", guideHtml], ["Reading Guide", readingGuideHtml], ["Maze Guide", mazeGuideHtml]]) {
  assert.doesNotMatch(source, /guide-beacon\.(?:css|js)/, `${route} should not load contextual Beacon assets`);
  assert.doesNotMatch(source, /data-guide-beacon-id=/, `${route} internal navigation should remain normal`);
}

assert.match(topbarJs, /vm-menu-link--utility/, "mobile Guide navigation should remain generated by the topbar owner");
assert.doesNotMatch(topbarJs, /vm-guide-beacon|data-guide-beacon-id/, "mobile navigation must not inherit Beacon treatment");
for (const source of [homeHtml, archscryHtml, mazeHtml, guideHtml, readingGuideHtml, mazeGuideHtml]) {
  assert.doesNotMatch(source, /class="vm-utility-link[^"]*vm-guide-beacon/, "desktop Guide utility must remain normal navigation");
}

assert.match(beaconCss, /\.vm-guide-beacon--entry[\s\S]*?\.vm-guide-beacon--compact[\s\S]*?\.vm-guide-beacon--maze/);
assert.match(beaconCss, /@keyframes vm-guide-beacon-signal[\s\S]*?6%[\s\S]*?37%[\s\S]*?68%/);
assert.match(beaconCss, /animation: vm-guide-beacon-signal 4800ms ease-in-out 1 both/);
assert.match(beaconCss, /\.vm-guide-beacon:hover,[\s\S]*?\.vm-guide-beacon:focus-visible/);
assert.match(beaconCss, /@media \(prefers-reduced-motion: reduce\)[\s\S]*?animation: none !important/);
assert.match(beaconCss, /\[data-reduce-motion="true"\][\s\S]*?animation: none !important/);

assert.match(beaconJs, /var seenBeaconIds = new Set\(\)/);
assert.match(beaconJs, /IntersectionObserver[\s\S]*?intersectionRatio >= 0\.55/);
assert.match(beaconJs, /MutationObserver[\s\S]*?childList: true, subtree: true/);
assert.match(beaconJs, /pointerenter[\s\S]*?focusin[\s\S]*?animationend/);
assert.match(beaconJs, /vm:reduce-motion-change/);
assert.doesNotMatch(beaconJs, /localStorage|sessionStorage|cookie|telemetry|analytics|Driver/i);

for (const [label, source] of [["Home", homeHtml], ["Archscry dossier", dossierView], ["Maze", mazeUi]]) {
  assert.match(source, /<a\b[\s\S]*?data-guide-beacon-id=/, `${label} fallback should remain an ordinary working link without JS`);
}

assert.equal(await stat(path.join(root, "guide", "reference")).then(() => true).catch(() => false), false, "/guide/reference/ must remain absent");

console.log("VM-620 shared Guide Beacon static contract tests passed.");
console.log(`Shared asset impact: CSS ${Buffer.byteLength(beaconCss)} bytes; JS ${Buffer.byteLength(beaconJs)} bytes.`);
